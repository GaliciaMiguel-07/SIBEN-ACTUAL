  <td>
  <h4>¿Para qué sirve?</h4>
  Para apoyar a la toma de decisiones así como actividades cotidianas de la DGESUM:
  <ul>
  <li>La planeación estratégica y operativa.</li>
  <li>Planeación y evaluación de documentos de las escuelas normales en el marco del EDINEN.</li>
  <li>Actualización del Directorio de las Instituciones Formadoras de Docentes.</li>
  <li>Información de base para el programa de becas y regulación de la educación normal.</li>
  <li>Estudios y aplicación de encuestas en estas instituciones.</li>
  <li>Conocimiento de las escuelas normales y su personal.</li>
  <li>Próximamente localizar geográficamente estas instituciones.</li>
  <li>Próximamente obtener datos de posgrados en las Instituciones Formadoras de Docentes.</li>
  </ul>
  </td>
  </tr>

  <tr class='info' id='t4' style='display:none;'>
  <td>
  <h4>Objetivo</h4>
  Contar con datos específicos, únicos y oficiales sobre la educación normal en
  México para la puesta en marcha de diferentes programas.

  <h4>Meta</h4>
  Tener la  participación del 100% de las escuelas en cada periodo de captura y generar
  así datos más certeros y precisos.
  </td>
  </tr>

  <tr class='info' id='t5' style='display:none;'>
  <td>
  <h4>¿Cómo opera?</h4>
  Todas las instituciones formadoras de docentes y la DGESUM intercambian
  directamente información para  mantenerla actualizada con la validación de
  las Autoridades Educativas Estatales.
  <ul>
  <li>La autoridad estatal nombra un enlace estatal y se le otorga una cuenta de usuario y contraseña.</li>
  <li>El director de cada escuela normal nombra un supervisor el cuál revisará los datos ingresados por el capturista, a éste también se le otorga una cuenta de usuario y contraseña</li>
  <li>El director de cada escuela normal nombra un capturista el cuál ingresará o actualizará los datos cada ciclo escolar, a éste también se le otorga una cuenta de usuario y contraseña</li>
  <li>La DGESUM a través de la Subdirección de Evaluación de Instituciones y Servicios mantendrá contacto con los enlaces estatales y dará a conocer el periodo de captura.</li>
  <li>Al final del primer periodo de captura del ciclo escolar, se enviarán firmados los informes que la DGESUM solicite.</li>
  </ul>

  </td>
