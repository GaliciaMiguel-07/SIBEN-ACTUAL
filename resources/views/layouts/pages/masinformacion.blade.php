    <h4>¿Qué es el SIBEN?</h4>
    <p>Es un programa que se utiliza para facilitar la consulta y actualización de la información
    de las Escuelas Normales a nivel nacional.  Concentra los principales datos de las escuelas,
    sus docentes y alumnos; además de fungir como un directorio en línea y ofrecer estadísticas
    de interés, disponibles a las escuelas normales y responsables de las normales. Próximamente
    permitirá obtener datos de las unidades y programas de posgrado que existen en las normales,
    también estará disponible una herramienta que permitirá ubicar localizar geográficamente las
    mismas escuelas.</p>
    </td>
  </tr>

  <tr class='info' id='t2' style='display:none;'>
  <td>
  <h4>Antecedentes</h4>
  <p>Hasta 2005 se recolectaba información de las escuelas normales mediante cuestionarios que se
  enviaban a las autoridades educativas locales en forma impresa y en disco magnético, éstas lo
  enviaban a las escuelas donde se llenaba el formato y se regresaba a la Dirección General, muchas
  veces estos formatos llegaban al finalizar el ciclo escolar lo que hacía poco oportuna la información,
  al llegar se capturaba en Access lo que implicaba una posible fuente de error por la misma captura,
  cuando se detectaba información inconsistente nadie en las autoridades educativas locales ni en las
  escuelas sabían quien se había hecho cargo del asunto, lo que impedía confirmar o corregir el dato,
  lo que nos lleva a entender que la información era poco confiable.</p>

  <p>Por lo anterior se decidió que fuera en línea lo que evita recapturas y permite tener bien
  identificadas a las personas responsables de la información, actualmente se otorga un mes para
  actualizar su información lo que hizo más breve el tiempo para tener los datos.</p>

  <p>El Sistema de Información Básica de la Educación Normal empezó su funcionamiento en el ciclo escolar
  2006-2007, donde se recababa la información más importante de los estudiantes y docentes frente a grupo.</p>

  <p>Como toda práctica nueva fue un poco complicado que todas las escuelas ingresaran y cargaran su información.</p>

  <p>A través de un enlace estatal que es el vínculo ente las normales y el SIBEN, y con la colaboración
  de un capturista y supervisor por escuela, se fue logrando que las escuelas normales fueran poco a poco
  ingresando sus datos, al principio se les solicitó del ciclo escolar y se recibieron todas las sugerencias
  para mejorar el sistema, actualmente se obtiene tres veces más información que en la primera versión.</p>

  <p>En el ciclo escolar 2006-2007 se obtuvo una participación de cerca del 80% de las escuelas normales que
  representaba al 60% de los estudiantes, para el ciclo escolar 2007-2008 se obtuvo una participación del 98%
  de las escuelas normales que representaba el 86% de los estudiantes, cabe hacer la mención que el sistema capta
  el nombre, apellidos y CURP de cada estudiante, al solicitar estos datos ya no se llegó a la cantidad que se
  tenía cuando sólo se solicitaba el número de estudiantes, lo que se pudo haber debido a que las escuelas
  sobredimensionaron su matrícula, esto lo obtenemos en conclusión debido a que para el ciclo escolar 2008-2009
  se obtuvo la participación de casi el 99% de las escuelas normales que representan el 98% de los estudiantes
  del ciclo escolar 2007-2008.</p>

  <p>Los tiempos de recuperación de información se redujeron de nueve meses  en promedio a un mes y la cantidad
  de información se ha incrementado tres veces del 2007 al 2009, y cada año se incorporan más datos de acuerdo
  con las necesidades de los usuarios. Derivado de estas necesidades se incorporan dos módulos adicionales al SIBEN,
  quedando ahora el módulo licenciaturas, el módulo posgrados y el módulo localización geográfica</p>

  <p>En octubre del 2009, se libera el SIBEN- Posgrados, que pretende compilar la información de programas, profesores
  y alumnos de posgrados en formación docente.</p>

  <p>Para la actualización de datos del ciclo escolar 2009-2010 también se incorpora el módulo de localización
  geográfica de las escuelas lo que facilita su ubicación para diferentes usos tanto de usuarios internos como
  externos</p>
  </td>
